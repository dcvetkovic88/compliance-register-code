// contracts/scripts/generate (plan D6; 111-FR5; S1149): for each synced OpenAPI file, the TypeScript types of
// openapi-typescript (<service>.types.ts) and one typed openapi-fetch client (<service>-client.ts). Runs at
// build; the output (--out, default contracts/generated/) is never committed and never edited by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { CONTRACTS_DIR, LOCK_NAME, contractsDir, parseOptions } from "./frozen.mjs";

const OPENAPI = /\.openapi\.ya?ml$/;

function header(source) {
  return `// Generated by contracts/scripts/generate from contracts/${source}. Never edit it; it is not committed.\n`;
}

function typeName(service) {
  return service
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function client(service, source) {
  const name = typeName(service);
  return [
    header(source).trimEnd(),
    'import createClient from "openapi-fetch";',
    `import type { paths } from "./${service}.types";`,
    "",
    `export type ${name}Client = ReturnType<typeof create${name}Client>;`,
    "",
    `export function create${name}Client(baseUrl: string) {`,
    "  return createClient<paths>({ baseUrl });",
    "}",
    "",
  ].join("\n");
}

const options = parseOptions(process.argv.slice(2));
const folder = contractsDir(options);
const out = path.resolve(options.out ?? path.join(CONTRACTS_DIR, "generated"));
const lock = JSON.parse(readFileSync(path.join(folder, LOCK_NAME), "utf8"));
mkdirSync(out, { recursive: true });
for (const source of Object.keys(lock.files).filter((name) => OPENAPI.test(name))) {
  const service = source.replace(OPENAPI, "");
  const types = astToString(await openapiTS(pathToFileURL(path.join(folder, source))));
  writeFileSync(path.join(out, `${service}.types.ts`), header(source) + types);
  writeFileSync(path.join(out, `${service}-client.ts`), client(service, source));
  console.log(`generate: ${source} -> ${service}.types.ts, ${service}-client.ts`);
}

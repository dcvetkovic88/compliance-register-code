"""Generation of the TypeScript types and one typed client per service for the web (T4.3; 111-FR5, 111-AC5; plan D6).

`contracts/scripts/generate [--out DIR]` writes, for each synced OpenAPI file, `<service>.types.ts` (the types of
openapi-typescript) and `<service>-client.ts` (a typed openapi-fetch client). It runs at build; the output, by
default `contracts/generated/`, is never committed and never edited by hand (S1149).
"""

import json
import subprocess
from pathlib import Path

import pytest
from conftest import CONTRACTS, run_script

pytestmark = pytest.mark.suite_111_B4

SERVICES = {
    "ai-document-service": "AiDocumentService",
    "ict-risk-service": "IctRiskService",
    "monitoring-service": "MonitoringService",
    "platform": "Platform",
    "register-service": "RegisterService",
    "web-bff": "WebBff",
}
HEADER = "Generated by contracts/scripts/generate from contracts/{source}. Never edit it; it is not committed."


@pytest.fixture(scope="module")
def generated(tmp_path_factory) -> Path:
    out = tmp_path_factory.mktemp("generated")
    result = run_script("generate", "--out", str(out))
    assert result.returncode == 0, result.stdout + result.stderr
    return out


def test_generate_writes_the_types_and_one_client_per_service(generated):
    expected = sorted([f"{name}.types.ts" for name in SERVICES] + [f"{name}-client.ts" for name in SERVICES])

    assert sorted(path.name for path in generated.iterdir()) == expected


def test_every_generated_file_says_it_is_generated_and_never_edited(generated):
    for name in SERVICES:
        for suffix in (".types.ts", "-client.ts"):
            first_line = (generated / f"{name}{suffix}").read_text(encoding="utf-8").splitlines()[0]
            assert HEADER.format(source=f"{name}.openapi.yaml") in first_line, name + suffix


def test_each_client_is_typed_by_the_paths_of_its_contract(generated):
    client = (generated / "platform-client.ts").read_text(encoding="utf-8")

    assert 'import type { paths } from "./platform.types";' in client
    assert "export function createPlatformClient(baseUrl: string)" in client
    assert "createClient<paths>({ baseUrl })" in client


def test_111_ac5_generated_clients_type_check_and_reject_a_path_outside_the_contract(generated):
    usage = "\n".join(
        [
            *(f'import {{ create{type_name}Client }} from "./{name}-client";' for name, type_name in SERVICES.items()),
            'const bff = createWebBffClient("http://localhost");',
            'export const session = bff.GET("/session");',
            "// @ts-expect-error a path the contract does not hold is a type error",
            'export const missing = bff.GET("/no-such-path");',
            *(f'export const {type_name[0].lower()}{type_name[1:]} = create{type_name}Client("http://localhost");'
              for name, type_name in SERVICES.items()),
            "",
        ]
    )
    (generated / "usage.ts").write_text(usage, encoding="utf-8")
    tsconfig = {
        "compilerOptions": {
            "strict": True,
            "noEmit": True,
            "target": "ES2022",
            "module": "ESNext",
            "moduleResolution": "Bundler",
            "skipLibCheck": True,
            "typeRoots": [],
            "paths": {"openapi-fetch": [str(CONTRACTS / "node_modules/openapi-fetch")]},
        },
        "include": ["*.ts"],
    }
    (generated / "tsconfig.json").write_text(json.dumps(tsconfig), encoding="utf-8")

    result = subprocess.run(
        [str(CONTRACTS / "node_modules/.bin/tsc"), "-p", str(generated / "tsconfig.json")],
        check=False,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_output_is_never_committed():
    ignored = subprocess.run(
        ["git", "-C", str(CONTRACTS), "check-ignore", "-q", "generated/platform.types.ts"], check=False
    )
    tracked = subprocess.run(
        ["git", "-C", str(CONTRACTS), "ls-files", "generated"], check=True, capture_output=True, text=True
    )

    assert ignored.returncode == 0
    assert tracked.stdout == ""


def test_generate_writes_to_contracts_generated_by_default():
    result = run_script("generate")

    assert result.returncode == 0, result.stdout + result.stderr
    assert (CONTRACTS / "generated/register-service-client.ts").is_file()
